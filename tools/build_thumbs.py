#!/usr/bin/env python3
"""Build small preview images ("thumbnails") for the picture files the site shows.

The published maps are print-quality PNGs (a poster is 6622 x 4677 px, ~3 MB).
Loading six of those just to draw 128 px thumbnails makes the map folder crawl on
a phone, so the site points its previews at the light copies generated here and
keeps the full-resolution file for viewing and downloading.

Where things go:

* source  : every picture under `content/**` (folder kuch bhi ho — apne aap mil jati hai)
* thumb   : `data/thumbs/<subject>/<folder>/<name>.png`  (max 640 px, stripped)
* manifest: `data/thumbs/manifest.json` — source SHA-256 + thumb size, so
  `--check` can prove the previews match the files that are actually published.

Resizing needs ImageMagick (`magick` or `convert`). The thumbnails are committed,
so the site and every test work without it — you only need it when a new picture
is added. ImageMagick ke bina bhi site toot-ti nahi: `tools/build_catalog.py`
phir asli picture ko hi halka preview maan kar dikha deta hai.

Run:

    python3 tools/build_thumbs.py            # (re)build what is missing or stale
    python3 tools/build_thumbs.py --check    # fail if a preview is missing or stale
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
THUMB_ROOT = ROOT / "data/thumbs"
MANIFEST = THUMB_ROOT / "manifest.json"
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp", ".svg", ".avif", ".gif"}
MAX_WIDTH = 640
MAX_BYTES = 600 * 1024


def find_magick() -> str | None:
    for name in ("magick", "convert"):
        found = shutil.which(name)
        if found:
            return found
    return None


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def thumb_path(source_rel: str) -> pathlib.Path:
    """`content/rajasthan-geography/map/.../a.png` -> `data/thumbs/rajasthan-geography/map/.../a.png`."""
    relative = pathlib.PurePosixPath(source_rel)
    return THUMB_ROOT.joinpath(*relative.parts[1:]).with_suffix(".png")


def image_records() -> list[dict]:
    """Har picture jo content/ ke neeche kisi bhi folder me rakhi ho — catalogue se azaad."""
    records = []
    for path in sorted(CONTENT.rglob("*")):
        if not path.is_file() or path.name.startswith("."):
            continue
        if path.suffix.lower() not in IMAGE_SUFFIXES:
            continue
        source = path.relative_to(ROOT).as_posix()
        records.append({"source": source, "path": path, "thumb": thumb_path(source)})
    return records


def make_thumb(magick: str, record: dict) -> bool:
    """Halka preview banao. Fail ho to False (catalog asli file hi dikha dega)."""
    record["thumb"].parent.mkdir(parents=True, exist_ok=True)
    command = [
        magick,
        str(record["path"]),
        "-resize", f"{MAX_WIDTH}x{MAX_WIDTH}>",
        "-strip",
        "-colors", "256",
        "-depth", "8",
        f"PNG8:{record['thumb']}",
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"WARN: preview nahi bana {record['source']} — website asli file dikha dega:\n"
              f"      {result.stderr.strip()}")
        record["thumb"].unlink(missing_ok=True)
        return False
    return True


def load_manifest() -> dict:
    if MANIFEST.is_file():
        return json.loads(MANIFEST.read_text(encoding="utf-8"))
    return {"schema_version": 1, "note": "Generated by tools/build_thumbs.py — do not hand-edit.", "thumbs": {}}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify previews exist and match the published pictures")
    args = parser.parse_args()

    records = image_records()
    manifest = load_manifest()
    entries = manifest.setdefault("thumbs", {})
    stale: list[str] = []
    built: list[str] = []
    magick = find_magick()

    for record in records:
        source_rel = record["source"]
        source_hash = sha256(record["path"])
        entry = entries.get(source_rel)
        fresh = (
            entry is not None
            and entry.get("sha256") == source_hash
            and record["thumb"].is_file()
            and record["thumb"].stat().st_size <= MAX_BYTES
        )
        if fresh:
            continue
        if args.check:
            stale.append(source_rel)
            continue
        if magick is None:
            print(
                "WARN: ImageMagick nahi mila — nayi pictures ke light preview skip hue.\n"
                "      Website phir bhi theek chalegi (asli file hi preview ban jayegi);\n"
                "      halka preview chahiye to `magick`/`convert` install karke "
                "`python3 tools/build_thumbs.py` chalao."
            )
            break
        if not make_thumb(magick, record):
            continue
        entries[source_rel] = {
            "thumb": record["thumb"].relative_to(ROOT).as_posix(),
            "sha256": source_hash,
            "bytes": record["thumb"].stat().st_size,
            "source_bytes": record["path"].stat().st_size,
        }
        built.append(source_rel)

    if args.check:
        if stale:
            print("FAIL: previews are missing or stale for:\n  - " + "\n  - ".join(stale))
            print("      run: python3 tools/build_thumbs.py")
            return 1
        print(f"PASS: {len(records)} image preview(s) match the published pictures.")
        return 0

    seen = set(entries)
    wanted = {record["source"] for record in records}
    for source in sorted(seen - wanted):
        entries.pop(source)
        thumb = thumb_path(source)
        if thumb.is_file():
            thumb.unlink()
    for record in records:
        if record["source"] in seen - wanted:
            record["thumb"].unlink(missing_ok=True)

    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if built:
        total = sum(entries[source]["bytes"] for source in built)
        print(f"built {len(built)} preview(s) ({total / 1024:.0f} KB total):")
        for source in built:
            entry = entries[source]
            print(f"  {entry['thumb']}  {entry['bytes'] / 1024:.0f} KB  (from {entry['source_bytes'] / 1024:.0f} KB)")
    else:
        print(f"PASS: all {len(records)} preview(s) were already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
