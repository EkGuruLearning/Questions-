#!/usr/bin/env python3
"""Write the list of published pages (`data/catalog/site-routes.txt`).

The website is plain HTML: home, the subject explorer and one page per folder,
generated by tools/build_pages.py. This script just records what got generated,
so the link validator and the tests check the real set instead of a hand-kept list.

    python3 tools/build_site_routes.py            # refresh the list
    python3 tools/build_site_routes.py --check    # fail if the list is out of date
"""
from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "data/catalog/site-routes.txt"
SKIP_TOP = {"maintainer", "tools", "tests", ".git", "node_modules", "public", ".vercel", ".cache", ".venv"}
HEADER = """# Published pages (GitHub Pages routes under /Questions-/).
# Generated by tools/build_site_routes.py from the HTML files on disk — do not edit by hand.
"""


def published_pages() -> list[str]:
    pages = []
    for path in ROOT.rglob("*.html"):
        relative = path.relative_to(ROOT)
        if relative.parts[0] in SKIP_TOP:
            continue
        pages.append(relative.as_posix())
    # home first, then the subject explorer, then everything else alphabetically
    priority = {"index.html": 0, "404.html": 1, "subjects/index.html": 2}
    return sorted(pages, key=lambda item: (priority.get(item, 3), item))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the list is stale")
    args = parser.parse_args()

    text = HEADER + "\n".join(published_pages()) + "\n"
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print("FAIL: data/catalog/site-routes.txt is out of date; run python3 tools/build_site_routes.py")
            return 1
        print("PASS: the published page list matches the HTML files on disk.")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote data/catalog/site-routes.txt — {len(published_pages())} page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
