# -*- coding: utf-8 -*-
"""
cn_pipeline.py — the AUTO-UPDATE pipeline.

Drop any question PDF into  Computer Network/Incoming/  (or pass --pdf/--dir) and run:

    python tools/cn_pipeline.py ingest                 # ingest everything in Incoming/
    python tools/cn_pipeline.py ingest --pdf path/to/new.pdf
    python tools/cn_pipeline.py ingest --dir some/folder
    python tools/cn_pipeline.py rebuild 2              # rebuild Topic 2 PDF+MD
    python tools/cn_pipeline.py rebuild --all
    python tools/cn_pipeline.py status                 # pending counts per topic

What it does, for every PDF:
  1. EXTRACT  — pull MCQs (clean English question + 4 options) via cn_extract
                (pymupdf text; RapidOCR fallback for scanned PDFs). Garbled Hindi
                is dropped (re-authored later during curation).
  2. CLASSIFY — assign each question to one of the 7 topics + sub-topic by CONTENT
                (cn_taxonomy.classify) — never by the unreliable page headers.
  3. DEDUPE   — skip questions already curated (tools/data/topicN_data.py) or
                already pending, using a normalised-text key.
  4. MERGE    — append new unique questions to tools/data/topicN_pending.py
                (marked "needs verification").
  5. REBUILD  — regenerate the affected topic PDF(s)+MD so the new questions show up
                in a clearly-marked "Pending Review" section at the end of each topic.

Curated (verified) questions live in tools/data/topicN_data.py and are the source of
truth rendered in the main body. Pending questions are rendered separately and must
be verified + moved into the curated file before they count.
"""
import os, sys, json, glob, re, importlib.util

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from cn_extract import extract_questions
from cn_taxonomy import TOPICS, topic_by_num, classify
import cn_build_topic

DATA_DIR = os.path.join(HERE, "data")
INCOMING = os.path.join(ROOT, "Computer Network", "Incoming")

# ---------------------------------------------------------------------------
def _norm_key(text):
    t = re.sub(r"[^a-z0-9 ]", " ", str(text).lower())
    return re.sub(r"\s+", " ", t).strip()

def _load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m

def curated_keys(topic_num):
    """Set of normalised question keys already curated for this topic."""
    p = os.path.join(DATA_DIR, f"topic{topic_num}_data.py")
    if not os.path.exists(p):
        return set()
    m = _load_module(p, f"topic{topic_num}_data")
    keys = set()
    for s in m.SECTIONS:
        for q in s["questions"]:
            keys.add(_norm_key(q["q"][0]))
    return keys

def load_pending(topic_num):
    p = os.path.join(DATA_DIR, f"topic{topic_num}_pending.py")
    if not os.path.exists(p):
        return []
    m = _load_module(p, f"topic{topic_num}_pending")
    return list(getattr(m, "PENDING", []))

def write_pending(topic_num, pending):
    p = os.path.join(DATA_DIR, f"topic{topic_num}_pending.py")
    header = ('# -*- coding: utf-8 -*-\n"""Auto-ingested questions for Topic %d — '
              'NEED VERIFICATION (answers/nukte/Hindi to be added during curation).\n'
              'Generated by tools/cn_pipeline.py. Do not edit by hand; re-run the pipeline."""\n\n'
              % topic_num)
    with open(p, "w", encoding="utf-8") as f:
        f.write(header)
        f.write("PENDING = " + json.dumps(pending, ensure_ascii=False, indent=1) + "\n")

# ---------------------------------------------------------------------------
def ingest_questions(questions, verbose=True):
    """Classify + dedupe + merge a list of extracted questions into pending files."""
    # load current pending + curated keys per topic
    pend = {t["num"]: load_pending(t["num"]) for t in TOPICS}
    pend_keys = {n: {_norm_key(q["q_en"]) for q in pend[n]} for n in pend}
    cur_keys = {t["num"]: curated_keys(t["num"]) for t in TOPICS}

    added = {t["num"]: 0 for t in TOPICS}
    skipped_dup = 0
    skipped_unclassified = 0
    touched = set()
    for q in questions:
        text = q["q_en"] + " " + " ".join(q["opts_en"])
        tn, sn = classify(text)
        if tn is None:
            skipped_unclassified += 1
            continue
        key = _norm_key(q["q_en"])
        if key in cur_keys[tn] or key in pend_keys[tn]:
            skipped_dup += 1
            continue
        pend[tn].append({
            "src": q["src"], "q_en": q["q_en"], "opts_en": q["opts_en"],
            "topic": tn, "subtopic": sn,
        })
        pend_keys[tn].add(key)
        added[tn] += 1
        touched.add(tn)

    for tn in touched:
        write_pending(tn, pend[tn])
    if verbose:
        for t in TOPICS:
            if added[t["num"]] or pend[t["num"]]:
                print(f"  Topic {t['num']} ({t['title'][:34]:34s}): +{added[t['num']]} new pending "
                      f"(total pending {len(pend[t['num']])})")
        print(f"  duplicates skipped: {skipped_dup} | unclassified skipped: {skipped_unclassified}")
    return added, touched

def ingest_pdf(path, verbose=True):
    if verbose:
        print(f"Ingesting: {os.path.basename(path)}")
    qs = extract_questions(path, verbose=verbose)
    return ingest_questions(qs, verbose=verbose)

def ingest_dir(dirpath, verbose=True):
    pdfs = sorted(glob.glob(os.path.join(dirpath, "*.pdf")))
    if not pdfs:
        print(f"No PDFs found in {dirpath}")
        return
    allq = []
    for p in pdfs:
        allq.extend(extract_questions(p, verbose=verbose))
    ingest_questions(allq, verbose=verbose)

# ---------------------------------------------------------------------------
def rebuild(nums, verbose=True):
    for n in nums:
        try:
            cn_build_topic.build_one(n, verbose=verbose)
        except SystemExit as e:
            print(f"  Topic {n}: {e}")

def status():
    print("Pending (auto-ingested, need verification) per topic:")
    for t in TOPICS:
        p = load_pending(t["num"])
        cur = len(curated_keys(t["num"]))
        print(f"  Topic {t['num']} — {t['title'][:40]:40s} curated={cur:3d}  pending={len(p):3d}")

# ---------------------------------------------------------------------------
def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__); return
    cmd = args[0]
    if cmd == "ingest":
        pdfs, dirp = [], None
        it = iter(args[1:])
        for a in it:
            if a == "--pdf":
                pdfs.append(next(it))
            elif a == "--dir":
                dirp = next(it)
        if dirp:
            ingest_dir(dirp)
        elif pdfs:
            allq = []
            for p in pdfs:
                allq.extend(extract_questions(p, verbose=True))
            ingest_questions(allq)
        else:
            ingest_dir(INCOMING)  # default: the Incoming drop folder
    elif cmd == "rebuild":
        rest = args[1:]
        if rest and rest[0] == "--all":
            nums = [t["num"] for t in TOPICS if os.path.exists(os.path.join(DATA_DIR, f"topic{t['num']}_data.py"))]
        else:
            nums = [int(x) for x in rest]
        rebuild(nums)
    elif cmd == "status":
        status()
    else:
        print(__doc__)

if __name__ == "__main__":
    main()
